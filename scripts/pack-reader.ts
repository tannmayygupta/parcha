/**
 * Reads the built reader (dist-reader/) and writes src/generated/reader-files.ts so the publisher
 * can bundle the reader into every snapshot without any runtime file access.
 */
import { readdirSync, readFileSync, statSync, writeFileSync, mkdirSync } from "node:fs";
import { join, relative } from "node:path";

const dir = "dist-reader";
const files: { path: string; content: string }[] = [];

function walk(d: string): void {
  for (const name of readdirSync(d)) {
    const full = join(d, name);
    if (statSync(full).isDirectory()) walk(full);
    else files.push({ path: relative(dir, full).split("\\").join("/"), content: readFileSync(full, "utf8") });
  }
}
walk(dir);

mkdirSync("src/generated", { recursive: true });
writeFileSync(
  "src/generated/reader-files.ts",
  `// AUTO-GENERATED by scripts/pack-reader.ts. Do not edit.\nimport type { BundledFile } from "../shared/snapshot";\nexport const READER_FILES: BundledFile[] = ${JSON.stringify(files)};\n`,
);
const total = files.reduce((n, f) => n + f.content.length, 0);
console.log(`packed ${files.length} reader files (${(total / 1024).toFixed(0)} KB):`);
for (const f of files) console.log(`  ${f.path}  ${(f.content.length / 1024).toFixed(1)} KB`);
